/// Whether an alter may set a key, and where.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Dynamic {
    /// Not in `ALL_DYNAMIC_CONFIGS`: the process reads it at startup, and an
    /// alter is refused with `Cannot update these configs dynamically`.
    ReadOnly,
    /// A cluster-wide default, which a named broker may also override.
    Cluster,
    /// `PER_BROKER_CONFIGS`: valid on a named broker alone.
    PerBroker,
}

use Dynamic::{Cluster, PerBroker, ReadOnly};

/// The value check `DynamicConfig.Broker.validate` applies to a dynamic key,
/// after the type parse.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Check {
    /// The type parse is the whole check.
    Free,
    /// `Range.atLeast(n)` on an `INT`, `SHORT` or `LONG`.
    AtLeast(i64),
    /// `ValidString.in(..)`.
    OneOf(&'static [&'static str]),
    /// `ValidList.anyNonDuplicateValues(false, false)`: a list that may be
    /// neither empty nor repeat an element. Every other `LIST` key allows the
    /// empty list.
    NonEmptyList,
}

use Check::{AtLeast, Free, NonEmptyList, OneOf};

/// One key of `AbstractKafkaConfig.CONFIG_DEF`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct KafkaBrokerConfig {
    pub(crate) name: &'static str,
    /// `ConfigKey.type`.
    pub(crate) config_type: ConfigType,
    /// `ConfigDef.convertToString` of `ConfigKey.defaultValue`; `None` is
    /// Kafka's `null`, and a key with no default at all.
    pub(crate) default: Option<&'static str>,
    pub(crate) dynamic: Dynamic,
    /// `ConfigKey.internalConfig`, which `KafkaConfig.nonInternalValues`
    /// leaves out of a named broker's `DescribeConfigs`.
    pub(crate) internal: bool,
    check: Check,
}

const fn k(
    name: &'static str,
    config_type: ConfigType,
    default: Option<&'static str>,
    dynamic: Dynamic,
    check: Check,
) -> KafkaBrokerConfig {
    KafkaBrokerConfig {
        name,
        config_type,
        default,
        dynamic,
        internal: false,
        check,
    }
}

/// [`k`] for a key Kafka defines with `defineInternal`.
const fn ki(
    name: &'static str,
    config_type: ConfigType,
    default: Option<&'static str>,
    dynamic: Dynamic,
    check: Check,
) -> KafkaBrokerConfig {
    KafkaBrokerConfig {
        internal: true,
        ..k(name, config_type, default, dynamic, check)
    }
}

