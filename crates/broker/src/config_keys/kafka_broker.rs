/// The roster row for `name`, when Kafka 4.3.1 defines it as a `KafkaConfig`
/// key.
pub(crate) fn lookup(name: &str) -> Option<&'static KafkaBrokerConfig> {
    KAFKA_BROKER_CONFIGS
        .binary_search_by(|row| row.name.cmp(name))
        .ok()
        .map(|index| &KAFKA_BROKER_CONFIGS[index])
}

/// Kafka's `LISTENER_MECHANISM_CONFIGS`: the keys a listener overrides under a
/// SASL mechanism prefix, as `listener.name.<listener>.<mechanism>.<key>`.
const LISTENER_MECHANISM_CONFIGS: &[&str] = &[
    "sasl.jaas.config",
    "sasl.login.callback.handler.class",
    "sasl.login.class",
    "sasl.server.callback.handler.class",
    "connections.max.reauth.ms",
];

/// The part of a `listener.name.<listener>.<rest>` override that follows the
/// listener name, which is Kafka's `LISTENER_CONFIG_REGEX` group.
pub(crate) fn listener_override_base(name: &str) -> Option<&str> {
    let rest = name.strip_prefix("listener.name.")?;
    let (_, base) = rest.split_once('.')?;
    Some(base)
}

/// The roster row that types `name`, as `KafkaConfig.configType` resolves it:
/// the key itself, else the key a `listener.name.<listener>.` override
/// overrides. A mechanism override such as `plain.sasl.jaas.config` resolves
/// to the mechanism-independent key it ends in.
pub(crate) fn resolve(name: &str) -> Option<&'static KafkaBrokerConfig> {
    lookup(name).or_else(|| {
        let rest = listener_override_base(name)?;
        let base = LISTENER_MECHANISM_CONFIGS
            .iter()
            .find(|mechanism| rest.ends_with(**mechanism))
            .copied()
            .unwrap_or(rest);
        lookup(base)
    })
}

impl KafkaBrokerConfig {
    /// The registry-shaped row `DescribeConfigs` shapes an entry from. The
    /// roster carries no documentation string, so the row has none.
    pub(crate) const fn row(&self) -> ConfigKey {
        ConfigKey {
            name: self.name,
            scope: ConfigScope::Broker,
            config_type: self.config_type,
            type_note: None,
            default: self.default,
            doc: "",
            read_only: matches!(self.dynamic, ReadOnly),
            sensitive: matches!(self.config_type, Password),
            internal: self.internal,
            kip: None,
            cluster_default: None,
            check: ValueCheck::Parsed,
        }
    }

    /// Kafka's `ConfigDef.parse` of one value of this key, returned in the
    /// form Kafka reports it: trimmed, a boolean in lower case, a number as it
    /// parses, a list joined with bare commas.
    ///
    /// A `CLASS` value is not loaded, because there is no JVM to load it
    /// into: Kafka would answer `Class <name> could not be found.` for a name
    /// its class path lacks, and this accepts the name.
    ///
    /// # Errors
    /// Returns Kafka's `ConfigException` text, which the alter paths answer
    /// with `INVALID_REQUEST`.
    pub(crate) fn canonical(&self, value: &str) -> Result<String, String> {
        let key = self.name;
        let at_least = |parsed: i64| match self.check {
            AtLeast(min) => check_range(key, parsed, Some(min), None),
            _ => Ok(parsed),
        };
        match self.config_type {
            Bool => parse_bool(key, value).map(|parsed| parsed.to_string()),
            Int => at_least(i64::from(parse_int(key, value)?)).map(|parsed| parsed.to_string()),
            Short => at_least(i64::from(parse_short(key, value)?)).map(|parsed| parsed.to_string()),
            Long => at_least(parse_long(key, value)?).map(|parsed| parsed.to_string()),
            Double => parse_double(key, value).map(java_double),
            Str => match self.check {
                OneOf(accepted) => check_one_of(key, value, accepted).map(str::to_owned),
                _ => Ok(java_trim(value).to_owned()),
            },
            Class | Password => Ok(java_trim(value).to_owned()),
            List => check_valid_list(key, value, &[], !matches!(self.check, NonEmptyList))
                .map(|values| values.join(",")),
        }
    }
}

