//! Apache Kafka 4.3.1's `KafkaConfig` key roster: every broker key the
//! released broker defines, with its `ConfigDef` type, its default, whether an
//! alter may set it dynamically, and the value check it applies.
//!
//! Three surfaces read it.
//!
//! - **The alter paths.** `DynamicBrokerConfig.validateConfigs` refuses every
//!   `KafkaConfig` key that is not dynamic, and `DynamicConfig.Broker.validate`
//!   parses and range-checks every key that is. A name the roster does not hold
//!   is not a `KafkaConfig` key, and Kafka stores it unchecked.
//! - **`DescribeConfigs`.** `KafkaConfig.configType` types a key by this //!   and `KafkaConfig.maybeSensitive` withholds the value of a `PASSWORD` key
//!   and of a name Kafka does not define. A named broker lists every
//!   non-internal key, at its default unless the process was started with a
//!   value.
//! - **`APPEND` and `SUBTRACT`**, which Kafka allows on a `LIST` key alone.
//!
//! # Where the rows come from
//!
//! The rows are `AbstractKafkaConfig.CONFIG_DEF` of the Apache Kafka 4.3.1
//! sources, which is the merge of the `CONFIG_DEF` of `RemoteLogManagerConfig`,
//! `ServerConfigs`, `KRaftConfigs`, `MetadataLogConfig`, `SocketServerConfigs`,
//! `ReplicationConfigs`, `GroupCoordinatorConfig`, `CleanerConfig`,
//! `LogConfig.SERVER_CONFIG_DEF`, `ShareGroupConfig`, `ShareCoordinatorConfig`,
//! `TransactionLogConfig`, `TransactionStateManagerConfig`, `QuorumConfig`,
//! `MetricConfigs`, `QuotaConfig`, `BrokerSecurityConfigs`,
//! `DelegationTokenManagerConfigs` and `AddPartitionsToTxnConfig`. They were
//! read out of the loaded `ConfigDef` objects (`ConfigKey.type`,
//! `defaultValue` through `ConfigDef.convertToString`, `internalConfig`), not
//! transcribed. 360 keys, 20 of them internal.
//!
//! The dynamic column is `DynamicBrokerConfig.ALL_DYNAMIC_CONFIGS` (99 of the
//! 360 keys), and the per-broker column is its `PER_BROKER_CONFIGS`:
//! `SslConfigs.RECONFIGURABLE_CONFIGS`, `DynamicListenerConfig`, and
//! `cordoned.log.dirs`, less the three cluster-level listener keys. The three
//! `QuotaConfig.brokerQuotaConfigs()` keys are dynamic too, but are not
//! `KafkaConfig` keys, so [`crate::throttle`] owns them.
//!
//! The check column carries only what an alter of a *dynamic* key can trip,
//! which is `Range.atLeast`, `ValidString.in` and `ValidList`. The topic
//! synonyms carry their topic key's own check instead (see
//! [`super::broker_dynamic`]), so a key with a stricter validator than the one
//! here is checked by that validator first.
//!
//! Kafka trunk's broker keys are not here. Under
//! `unstable.api.versions.enable`, [`super::broker_dynamic`] adds the broker
//! synonyms of trunk's topic keys on top of this roster.

